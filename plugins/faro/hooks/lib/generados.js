// lib/generados.js — LISTA UNICA de lo que NO es codigo del equipo para las senales de salud
// (atomicidad en lib/atomico.js y grafo de ciclos/huerfanos en lib/grafo.js). (#126)
//
// Por que existe: las dos senales recorrian el arbol cada una con su propia lista de exclusion, y
// ninguna conocia los ficheros que GENERAN las herramientas. Caso real (un monorepo):
// ATOMICIDAD listaba apps/api/worker-configuration.d.ts (15.292 lineas, de `wrangler types`) y el
// detector de ciclos senalaba apps/web/src/routeTree.gen.ts (TanStack Router). Nadie va a "separar
// por concepto" un fichero que regenera una herramienta: es ruido que tapa la deuda real.
//
// Esta lista se aplica SIEMPRE, aunque el repo declare su propio enums.atomicidad.excluir: el
// `excluir` del contrato es para lo que el equipo decida apartar; lo generado nunca es suyo.
// Se compara por SEGMENTO de ruta, asi que vale igual en la raiz que en apps/<x>/... (monorepo).
'use strict';

const { spawnSync } = require('child_process');

// Carpetas de build, caches de herramientas y dependencias, en cualquier nivel del arbol.
const CARPETAS = new Set(['node_modules', 'dist', 'build', '.wrangler', '.tanstack', '.git']);
// Ficheros generados reconocibles por el NOMBRE.
const NOMBRES = [
  /\.gen\.(d\.)?[cm]?[jt]sx?$/i,          // routeTree.gen.ts (TanStack Router) y familia *.gen.*
  /^worker-configuration\.d\.ts$/i,       // `wrangler types`
];
// Un .d.ts hecho a mano es legitimo; uno generado lo declara en su cabecera.
const CABECERA_GENERADA = /@generated|auto-?generated|automatically generated|generated by|do not edit/i;

// excluidoPorRuta('apps/web/dist/x.js') -> true. Vale para carpetas y ficheros.
function excluidoPorRuta(rel) {
  const seg = String(rel).split('/');
  if (seg.some((s) => CARPETAS.has(s))) return true;
  const nombre = seg[seg.length - 1];
  return NOMBRES.some((re) => re.test(nombre));
}

// .d.ts cuya cabecera (primeras lineas) dice que lo genero una herramienta.
function dtsGenerado(abs, fs) {
  let cab = '';
  try {
    const fd = fs.openSync(abs, 'r');
    try { const b = Buffer.alloc(600); cab = b.toString('utf8', 0, fs.readSync(fd, b, 0, 600, 0)); } finally { fs.closeSync(fd); }
  } catch { return false; }
  return CABECERA_GENERADA.test(cab.split(/\r?\n/).slice(0, 5).join('\n'));
}

// Ficheros que git IGNORA (no versionados por decision del repo: suelen ser salidas de build o
// clientes generados). Una sola llamada para toda la lista. Sin git o fuera de un repo: ninguno.
function ignoradosPorGit(root, rels) {
  if (!rels.length) return new Set();
  const r = spawnSync('git', ['-C', root, 'check-ignore', '--stdin'], { input: rels.join('\n'), encoding: 'utf8', timeout: 10000, windowsHide: true });
  if (!r || (r.status !== 0 && r.status !== 1) || !r.stdout) return new Set();
  return new Set(r.stdout.split(/\r?\n/).map((l) => l.trim()).filter(Boolean));
}

// depurar(root, rels, fs, path) -> rels sin lo ignorado por git ni los .d.ts generados.
// Complementa a excluidoPorRuta (que se aplica durante el recorrido, para no entrar en carpetas).
function depurar(root, rels, fs, path) {
  const ign = ignoradosPorGit(root, rels);
  return rels.filter((rel) => !ign.has(rel)
    && !(/\.d\.[cm]?ts$/i.test(rel) && dtsGenerado(path.join(root, rel), fs)));
}

module.exports = { excluidoPorRuta, depurar, ignoradosPorGit, CARPETAS, NOMBRES };
