// Cambio 'salud-codigo-ignora-generados' (#126): atomicidad y grafo (ciclos/huerfanos) NO cuentan
// ficheros generados por herramientas. Caso real: en un monorepo Cloudflare, ATOMICIDAD listaba
// apps/api/worker-configuration.d.ts (15.292 lineas, de `wrangler types`) y el detector de ciclos
// senalaba apps/web/src/routeTree.gen.ts (TanStack Router). Un test por escenario del delta.
import { test } from 'node:test';
import assert from 'node:assert';
import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const RAIZ = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const HARNESS = path.join(RAIZ, 'plugins', 'faro', 'hooks', 'harness.js');

const run = (args, cwd) =>
  spawnSync(process.execPath, args, { cwd, encoding: 'utf8', env: { ...process.env, CLAUDE_PROJECT_DIR: cwd }, timeout: 60000 });

// Monorepo con ficheros generados en apps/<x>/ (no en la raiz) y deuda REAL de control, para
// comprobar que la exclusion no se come lo que si es codigo del equipo.
function monorepo({ schema } = {}) {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'faro-generados-'));
  const git = (...a) => spawnSync('git', a, { cwd: dir, encoding: 'utf8' });
  git('init', '-q');
  git('config', 'user.email', 'test@example.com');
  git('config', 'user.name', 'Test');
  git('config', 'commit.gpgsign', 'false');
  git('config', 'tag.gpgsign', 'false');
  git('remote', 'add', 'origin', 'git@github.com:x/y.git');
  const f = {
    // Generado por wrangler types: 15.000 lineas.
    'apps/api/worker-configuration.d.ts':
      '// Generated by Wrangler by running `wrangler types`\n' + 'interface Env { X: string }\n'.repeat(15000),
    // .d.ts generado por otra herramienta: lo delata su cabecera.
    'apps/api/src/tipos-db.d.ts':
      '// This file is auto-generated. Do not edit.\n' + 'type T = 1;\n'.repeat(600),
    'apps/api/src/index.ts': "import { util } from './util';\nexport default util;\n",
    'apps/api/src/util.ts': 'export const util = 1;\n',
    // Deuda REAL: debe seguir saliendo.
    'apps/api/src/grande.ts': "import { util } from './util';\n" + 'export const a = 1;\n'.repeat(500),
    // TanStack Router: routeTree.gen.ts en ciclo con una ruta.
    'apps/web/src/routeTree.gen.ts':
      "/* eslint-disable */\n// This file was automatically generated by TanStack Router.\nimport { Route } from './routes/index';\nexport const routeTree = Route;\n" +
      'export const r = 1;\n'.repeat(600),
    'apps/web/src/routes/index.tsx': "import { routeTree } from '../routeTree.gen';\nexport const Route = routeTree;\n",
    'apps/web/src/main.tsx': "import { routeTree } from './routeTree.gen';\nexport default routeTree;\n",
    // Ciclo REAL entre modulos del equipo: debe seguir saliendo.
    'apps/web/src/x.ts': "import { y } from './y';\nexport const x = y;\n",
    'apps/web/src/y.ts': "import { x } from './x';\nexport const y = x;\n",
    // Carpetas de build / cache de herramientas, dentro de apps/<x>/.
    'apps/web/dist/assets/bundle.js': 'var z = 1;\n'.repeat(3000),
    'apps/web/build/server.js': 'var z = 1;\n'.repeat(3000),
    'apps/api/.wrangler/tmp/bundle.js': 'var z = 1;\n'.repeat(3000),
    'apps/web/.tanstack/tmp/rutas.ts': 'export const t = 1;\n'.repeat(3000),
    'apps/web/node_modules/pkg/index.js': 'var z = 1;\n'.repeat(3000),
    // Ignorado por git (no versionado), aunque su nombre no delate nada.
    'apps/web/src/cliente-api.ts': 'export const c = 1;\n'.repeat(3000),
    'apps/web/.gitignore': 'src/cliente-api.ts\n',
    'README.md': '# t\n',
  };
  if (schema) f['.claude/faro-schema.json'] = JSON.stringify(schema);
  for (const [rel, txt] of Object.entries(f)) {
    fs.mkdirSync(path.join(dir, path.dirname(rel)), { recursive: true });
    fs.writeFileSync(path.join(dir, rel), txt);
  }
  git('add', '-A');
  git('commit', '-q', '-m', 'init');
  return dir;
}

const GENERADOS = [
  'worker-configuration.d.ts', 'tipos-db.d.ts', 'routeTree.gen', 'dist/', 'build/', '.wrangler/',
  '.tanstack/', 'node_modules/', 'cliente-api.ts',
];
const nombraGenerado = (txt) => GENERADOS.filter((g) => txt.includes(g));

test('atomicidad: no lista ficheros generados del monorepo, si la deuda real', () => {
  const dir = monorepo();
  const r = run([HARNESS, 'atomico'], dir);
  assert.strictEqual(r.status, 0, r.stderr);
  assert.deepStrictEqual(nombraGenerado(r.stdout), [], `nombra generados:\n${r.stdout}`);
  assert.match(r.stdout, /apps\/api\/src\/grande\.ts/, 'la deuda real debe seguir saliendo');
});

test('grafo: el ciclo con routeTree.gen.ts no se reporta; el ciclo real si', () => {
  const dir = monorepo();
  const r = run([HARNESS, 'codigo'], dir);
  assert.strictEqual(r.status, 0, r.stderr);
  assert.deepStrictEqual(nombraGenerado(r.stdout), [], `nombra generados:\n${r.stdout}`);
  assert.match(r.stdout, /1 ciclo\(s\)/, r.stdout);
  assert.match(r.stdout, /apps\/web\/src\/x\.ts/);
});

// Desde #127 el arranque es un indice con presupuesto: la salud de codigo es un aviso de prioridad
// baja y puede recortarse (con puntero a 'estado'). Donde vive siempre es el bloque completo,
// 'harness.js estado'; el indice, si la trae, tampoco puede nombrar generados.
test('sesion: ninguna senal de salud nombra un fichero generado', () => {
  const dir = monorepo();
  const r = run([HARNESS, 'estado'], dir);
  assert.strictEqual(r.status, 0, r.stderr);
  const salud = r.stdout.split('\n').filter((l) => /ATOMICIDAD|CICLOS DE DEPENDENCIA/.test(l)).join('\n');
  assert.match(salud, /ATOMICIDAD/, 'la deuda real debe anunciarse');
  assert.match(salud, /CICLOS DE DEPENDENCIA[^\n]*apps\/web\/src\/x\.ts/, 'el ciclo real debe anunciarse');
  assert.deepStrictEqual(nombraGenerado(salud), [], `nombra generados:\n${salud}`);
  const indice = run([HARNESS, 'session'], dir);
  assert.strictEqual(indice.status, 0, indice.stderr);
  const saludIndice = indice.stdout.split('\\n').filter((l) => /ATOMICIDAD|CICLOS DE DEPENDENCIA/.test(l)).join('\n');
  assert.deepStrictEqual(nombraGenerado(saludIndice), [], `el indice nombra generados:\n${saludIndice}`);
});

test('la exclusion de generados se aplica aunque el repo declare su propio excluir', () => {
  const dir = monorepo({ schema: { enums: { atomicidad: { max_lineas: 400, extensiones: ['.ts', '.tsx', '.js'], excluir: [] } } } });
  const r = run([HARNESS, 'codigo'], dir);
  assert.strictEqual(r.status, 0, r.stderr);
  assert.deepStrictEqual(nombraGenerado(r.stdout), [], `nombra generados:\n${r.stdout}`);
  assert.match(r.stdout, /grande\.ts/);
});
